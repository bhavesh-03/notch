import AppKit
import ImageIO
import UniformTypeIdentifiers

/// Keeps a preview of the latest supported clipboard item in memory while the feature is enabled.
@Observable
final class ClipboardMonitor {
    enum Payload {
        case image(NSImage)
        case files([URL])
        case text(String)
    }

    struct Entry: Identifiable {
        let id = UUID()
        let content: Payload
    }

    private(set) var entry: Entry?
    @ObservationIgnored var onChange: (() -> Void)?
    @ObservationIgnored private var watchTask: Task<Void, Never>?

    func start(pasteboard: NSPasteboard = .general) {
        guard watchTask == nil else { return }
        let initialCount = pasteboard.changeCount
        watchTask = Task { [weak self] in
            var changeCount = initialCount
            while !Task.isCancelled {
                try? await Task.sleep(for: .milliseconds(350))
                guard !Task.isCancelled, let self else { break }
                let count = pasteboard.changeCount
                guard count != changeCount else { continue }
                changeCount = count
                entry = Self.preview(from: pasteboard).map { Entry(content: $0) }
                onChange?()
            }
        }
    }

    func stop() {
        watchTask?.cancel()
        watchTask = nil
        entry = nil
    }

    static func preview(from pasteboard: NSPasteboard) -> Payload? {
        let excluded = [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType"
        ].map { NSPasteboard.PasteboardType($0) }
        guard pasteboard.availableType(from: excluded) == nil else { return nil }

        if let files = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !files.isEmpty {
            return .files(files)
        }

        for type in pasteboard.types ?? [] {
            guard UTType(type.rawValue)?.conforms(to: .image) == true,
                  let data = pasteboard.data(forType: type),
                  let source = CGImageSourceCreateWithData(data as CFData, nil),
                  let image = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                    kCGImageSourceCreateThumbnailFromImageAlways: true,
                    kCGImageSourceCreateThumbnailWithTransform: true,
                    kCGImageSourceThumbnailMaxPixelSize: 320
                  ] as CFDictionary)
            else { continue }
            return .image(NSImage(cgImage: image, size: NSSize(width: image.width, height: image.height)))
        }

        if let text = pasteboard.string(forType: .string) ?? pasteboard.string(forType: .URL),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return .text(String(text.prefix(2_000)))
        }
        return nil
    }
}
